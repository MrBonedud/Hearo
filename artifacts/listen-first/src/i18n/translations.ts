export const messages: Record<Language, Record<TranslationKey, string>> = { en, ar };

const warned = new Set<string>();
function warnMissing(language: Language, key: string) {
  if (!import.meta.env?.DEV || warned.has(`${language}:${key}`)) return;
  warned.add(`${language}:${key}`);
  console.warn(`[i18n] Missing "${key}" for "${language}"; using a fallback.`);
}

/** Looks up `key`, falling back to English and then to the key itself. */
export function translate(language: Language, key: TranslationKey, vars?: TranslationVars): string {
  let template = messages[language]?.[key];
  if (template === undefined) {
    warnMissing(language, key);
    template = en[key] ?? key;
  }
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    if (value === undefined) return match;
    return typeof value === 'number' ? formatNumber(language, value) : value;
  });
}
